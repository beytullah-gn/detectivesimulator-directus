// Builds an idempotent SQL file from scripts/content/cases/*.json and the game extension's default prompts.
// Usage: node scripts/content/build-content-sql.mjs > case-content.sql
import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";

const root = new URL("./", import.meta.url);
const caseDir = new URL("cases/", root);

function sql(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "boolean") return value ? "1" : "0";
  if (typeof value === "number") return String(value);
  const text = typeof value === "string" ? value : JSON.stringify(value);
  return `'${text.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n")}'`;
}

// Stable UUID (v5 layout) so re-running the script updates instead of duplicating new evidence.
function stableUuid(name) {
  const hash = createHash("sha1").update(`detectivesimulator:${name}`).digest("hex");
  const variant = ((parseInt(hash[16], 16) & 0x3) | 0x8).toString(16);
  return `${hash.slice(0, 8)}-${hash.slice(8, 12)}-5${hash.slice(13, 16)}-${variant}${hash.slice(17, 20)}-${hash.slice(20, 32)}`;
}

function assignments(fields) {
  return Object.entries(fields)
    .filter(([, value]) => value !== undefined)
    .map(([column, value]) => `${column} = ${sql(value)}`)
    .join(", ");
}

function readDefaultPrompts() {
  const source = readFileSync(new URL("../../extensions/game/src/index.js", root), "utf8");
  const start = source.indexOf("const DEFAULT_PROMPTS = {");
  const end = source.indexOf("\n};\n", start) + 3;
  return new Function(`${source.slice(start, end)}\nreturn DEFAULT_PROMPTS;`)();
}

const lines = ["-- Generated by scripts/content/build-content-sql.mjs", "START TRANSACTION;"];
const caseFiles = readdirSync(caseDir).filter((file) => file.endsWith(".json")).sort();

for (const file of caseFiles) {
  const data = JSON.parse(readFileSync(new URL(file, caseDir), "utf8"));
  const scenarioId = `(SELECT id FROM (SELECT id FROM scenarios WHERE slug = ${sql(data.slug)}) AS s)`;
  lines.push(`\n-- ${data.slug}`);
  lines.push(`UPDATE scenarios SET ${assignments(data.scenario)} WHERE slug = ${sql(data.slug)};`);

  for (const { id, ...fields } of data.characters || []) {
    lines.push(`UPDATE characters SET ${assignments(fields)} WHERE id = ${sql(id)};`);
  }

  for (const { id, relation } of data.relations || []) {
    lines.push(`UPDATE relations SET relation = ${sql(relation)} WHERE id = ${sql(id)};`);
  }

  for (const { id, key, ...fields } of data.evidence || []) {
    const row = {
      sort: fields.sort,
      type: fields.type,
      title: fields.title,
      description: fields.description,
      content: fields.content,
      media_url: fields.media_url || null,
      is_key_evidence: Boolean(fields.is_key_evidence),
    };
    if (id) {
      lines.push(`UPDATE scenario_media SET ${assignments(row)} WHERE id = ${sql(id)};`);
    } else {
      const newId = stableUuid(`${data.slug}:${key}`);
      const columns = ["id", "status", "date_created", "related_scenario", ...Object.keys(row)];
      const values = [sql(newId), "'published'", "NOW()", scenarioId, ...Object.values(row).map(sql)];
      lines.push(
        `INSERT INTO scenario_media (${columns.join(", ")}) VALUES (${values.join(", ")}) ON DUPLICATE KEY UPDATE ${assignments(row)};`
      );
    }
  }

  for (const { id, ...fields } of data.hints || []) {
    lines.push(`UPDATE hints SET ${assignments({ ...fields, media_url: fields.media_url || null })} WHERE id = ${sql(id)};`);
  }
}

const prompts = readDefaultPrompts();
lines.push("\n-- prompts");
lines.push(
  `UPDATE ai_prompts SET system_prompt = ${sql(prompts.detective_interrogation)}, messages = '[]' WHERE name = 'detective_interrogation';`
);
lines.push(
  `INSERT INTO ai_prompts (id, status, name, description, system_prompt, messages) SELECT ${sql(stableUuid("prompt:detective_final_review"))}, 'published', 'detective_final_review', 'Single-call final verdict and commissioner feedback.', ${sql(prompts.detective_final_review)}, '[]' FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM ai_prompts WHERE name = 'detective_final_review');`
);
lines.push(
  `UPDATE ai_prompts SET system_prompt = ${sql(prompts.detective_final_review)} WHERE name = 'detective_final_review';`
);
lines.push("COMMIT;");
process.stdout.write(`${lines.join("\n")}\n`);
